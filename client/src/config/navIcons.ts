export type NavIconKey = keyof typeof NAV_ICONS

/** 页面级图标缺失时的兜底 */
export const DEFAULT_NAV_ICON: NavIconKey = 'FileText'

export function isNavIconKey(name: string | undefined | null): name is NavIconKey {
  return !!name && Object.prototype.hasOwnProperty.call(NAV_ICONS, name)
}

/** 按键名取图标组件，未知键返回兜底图标 */
export function resolveNavIcon(name?: string | null): Component {
  return isNavIconKey(name) ? NAV_ICONS[name] : NAV_ICONS[DEFAULT_NAV_ICON]
}
